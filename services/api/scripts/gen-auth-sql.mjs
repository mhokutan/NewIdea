// Prints the CREATE TABLE statements Better Auth needs, using an in-memory SQLite with the same options.
// Run: node scripts/gen-auth-sql.mjs > migrations/0001_auth.sql
import { DatabaseSync } from "node:sqlite";
import { getMigrations } from "better-auth/db/migration";
import { authOptions } from "../src/auth.js";

const opts = authOptions({ BETTER_AUTH_SECRET: "x".repeat(32) }, new DatabaseSync(":memory:"), async () => {});
const { compileMigrations } = await getMigrations(opts);
console.log("-- Generated by scripts/gen-auth-sql.mjs (Better Auth tables)\n" + (await compileMigrations()));
